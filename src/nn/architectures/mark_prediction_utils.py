"""
Pure mark-prediction tensor utilities for TPP architectures.

All functions are stateless and shared across mark-aware architectures. They
handle:
- target masking for mark metrics
- target preparation for next-mark supervision
- mark-classification loss and accuracy computation
- mark diagnostic plot tensor preparation
- baseline logit construction (majority class and empirical distribution)
"""

import logging
import typing

import torch
import torch.nn.functional as F

logger = logging.getLogger(__name__)

MARK_IGNORE_INDEX = -1


class MarkEvalTensors(typing.NamedTuple):
    """Ready-to-consume output from ``_build_mark_eval_tensors``."""

    logits: torch.Tensor  # (N, L-1, num_marks)
    previous_marks: torch.Tensor  # (N, L-1), masked
    current_targets: torch.Tensor  # (N, L-1), masked


def compute_majority_class(
    train_marks: torch.Tensor,
    data_train_lens: torch.Tensor,
    num_marks: int,
) -> int:
    """Return the majority next-mark class index over valid prediction targets."""
    _, current_targets, valid_lengths = prepare_next_mark_prediction_tensors(train_marks, data_train_lens - 1)
    counts = count_valid_mark_targets(current_targets, valid_lengths, num_marks)
    return counts.argmax().item()


def extract_marks_without_anchor_from_batch(
    batch: typing.Tuple[torch.Tensor, torch.Tensor, torch.Tensor],
) -> torch.Tensor:
    """Always returns the marks tensor from batch position 2, stripping the anchor.

    Batch is always a 3-tuple (data, lengths, marks). Callers gate CE-loss
    computation on ``self.use_marks`` rather than checking for None.
    """
    return batch[2][:, 1:]


def prepare_next_mark_prediction_tensors(
    marks_with_anchor: torch.Tensor,
    event_lengths: torch.Tensor,
) -> typing.Tuple[torch.Tensor, torch.Tensor, torch.Tensor]:
    """Build the canonical next-mark prediction tensors from anchored marks.

    Args:
        marks_with_anchor: (N, L+1) long tensor including the anchor mark at column 0.
        event_lengths: (N,) long tensor giving the number of valid event positions
            in ``marks_with_anchor[:, 1:]``.

    Returns:
        Tuple ``(previous_marks, current_targets, valid_lengths)`` where:
            - ``previous_marks``: (N, L-1), marks at event positions 1..L-1
            - ``current_targets``: (N, L-1), marks at event positions 2..L
            - ``valid_lengths``: (N,), number of valid next-mark targets per sequence
    """
    # Targets start at event 2 (index 2 in anchored tensor) because τ₁ is always
    # seeded from training data, not generated by the model.  Only L-1 pairs are
    # supervised.  See TPPArchitecture._sample_first_event and sample_and_fix_seqs.
    previous_marks = marks_with_anchor[:, 1:-1].clone()
    current_targets = marks_with_anchor[:, 2:].clone()
    valid_lengths = (event_lengths - 1).clamp_min(0)
    return previous_marks, current_targets, valid_lengths


def mask_mark_targets(
    mark_targets: torch.Tensor,
    valid_lengths: torch.Tensor,
) -> torch.Tensor:
    """Replace padded positions with ``MARK_IGNORE_INDEX``.

    Args:
        mark_targets: (N, L) integer mark targets.
        valid_lengths: (N,) number of valid positions per sequence.

    Returns:
        Masked copy of ``mark_targets`` with padding set to the ignore index.
    """
    pos = torch.arange(mark_targets.shape[1], device=valid_lengths.device).unsqueeze(0)
    valid_mask = pos < valid_lengths.unsqueeze(1)
    masked_targets = mark_targets.clone()
    masked_targets[~valid_mask] = MARK_IGNORE_INDEX
    return masked_targets


def count_valid_mark_targets(
    mark_targets: torch.Tensor,
    valid_lengths: torch.Tensor,
    num_marks: int,
) -> torch.Tensor:
    """Count valid mark targets after masking padding positions."""
    masked_targets = mask_mark_targets(mark_targets, valid_lengths)
    valid_targets = masked_targets[masked_targets != MARK_IGNORE_INDEX]
    return torch.bincount(valid_targets, minlength=num_marks)


def prepare_next_mark_targets(
    marks: torch.Tensor,
    lengths: torch.Tensor,
) -> torch.Tensor:
    """Build masked next-mark targets from marks WITHOUT the anchor.

    ``marks`` must already have the anchor stripped (use
    ``extract_marks_without_anchor_from_batch`` before calling this).

    Args:
        marks: (N, L) mark tensor WITHOUT the anchor, i.e. marks[1..L].
        lengths: (N,) number of valid events (= number of valid inter-arrival
            times, *not* anchored positions).

    Returns:
        (N, L-1) next-mark targets with padding set to ``MARK_IGNORE_INDEX``.
        Position ``i`` is the mark of event ``i+2`` (target for predicting
        the next mark given history up to event ``i+1``).
    """
    return mask_mark_targets(marks[:, 1:].clone(), lengths - 1)


def compute_mark_ce_from_logits(
    mark_logits: torch.Tensor,
    marks: torch.Tensor,
    lengths: torch.Tensor,
) -> torch.Tensor:
    """Compute masked cross-entropy for next-mark prediction."""
    mark_targets = prepare_next_mark_targets(marks, lengths)
    return F.cross_entropy(
        mark_logits.reshape(-1, mark_logits.shape[-1]),
        mark_targets.reshape(-1),
        ignore_index=MARK_IGNORE_INDEX,
    )


@torch.no_grad()
def compute_mark_accuracy_metrics(
    mark_logits: torch.Tensor,
    masked_targets: torch.Tensor,
    *,
    include_top3: bool,
) -> typing.Dict[str, torch.Tensor]:
    """Compute top-k mark accuracies from logits and pre-masked targets."""
    # Local import to break circular dependency: mark_accuracy imports MARK_IGNORE_INDEX from here.
    from src.metrics.mark_accuracy import top_k_accuracy

    metrics = {
        'top1_mark_acc': top_k_accuracy(mark_logits, masked_targets, k=1),
    }
    if include_top3 and mark_logits.shape[-1] >= 3:
        metrics['top3_mark_acc'] = top_k_accuracy(mark_logits, masked_targets, k=3)
    return metrics


@torch.no_grad()
def compute_next_mark_accuracy_metrics(
    mark_logits: torch.Tensor,
    marks: torch.Tensor,
    lengths: torch.Tensor,
    *,
    include_top3: bool = True,
) -> typing.Dict[str, torch.Tensor]:
    """Compute next-mark accuracies directly from anchored marks and lengths."""
    mark_targets = prepare_next_mark_targets(marks, lengths)
    return compute_mark_accuracy_metrics(
        mark_logits,
        mark_targets,
        include_top3=include_top3,
    )


def build_majority_class_logits(
    mark_targets: torch.Tensor,
    num_marks: int,
    majority_class: int,
) -> torch.Tensor:
    """Build constant logits with all mass on the majority class.

    Args:
        mark_targets: (N, L) tensor used only for shape and device.
        num_marks: number of mark classes.
        majority_class: index of the majority class.

    Returns:
        (N, L, num_marks) logits tensor.
    """
    N, L = mark_targets.shape
    logits = torch.zeros(N, L, num_marks, device=mark_targets.device)
    # Use a large finite logit so downstream softmax is effectively one-hot.
    logits[:, :, majority_class] = 1e4
    return logits


def build_empirical_mark_logits(
    mark_probs: torch.Tensor,
    N: int,
    L: int,
) -> torch.Tensor:
    """Build log-probability logits from an empirical mark distribution.

    Args:
        mark_probs: (num_marks,) probability vector.
        N: batch size.
        L: sequence length.

    Returns:
        (N, L, num_marks) log-probability logits tensor.
    """
    return mark_probs.clamp(min=1e-10).log().unsqueeze(0).unsqueeze(0).expand(N, L, -1)
